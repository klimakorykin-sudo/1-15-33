(function() {
    'use strict';

    window.Message = {
        lines: [
            'Аня...',
            'Ты — самое тёплое, что случилось в этом мире.',
            'Ты — свет, который согревает даже холодные дни.',
            'Ты — чудо. Настоящее.',
            'Спасибо, что ты есть.'
        ],
        
        getFull() {
            return this.lines.join('\n');
        },
        
        getLine(index) {
            return this.lines[index] || '';
        },
        
        getCount() {
            return this.lines.length;
        }
    };

})();